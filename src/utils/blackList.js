export const isValidProductName = (productName, blacklistedWords = BLACKLISTED_PRODUCT_NAMES) => {
 if (!productName) return false;

 const normalizedName = productName.toUpperCase();

 const hasBlacklistedWord = blacklistedWords.some(word =>
     normalizedName.includes(word.toUpperCase())
 );

 return !hasBlacklistedWord;
};

export const matchesSearchTerm = (productName, searchTerm) => {
 if (!searchTerm) return true; // если поиска нет, показываем всё
 if (!productName) return false;

 return productName.toLowerCase().includes(searchTerm.toLowerCase());
};